/**
 * dtc plugin —— 通道打包：单一源码（plugin/src）构建四种长期可安装形态。
 *
 *  1. desktop/        Figma 桌面 App 开发插件（Import from manifest，一次导入永久用）
 *  2. chrome-extension/ + dtc-bridge-chrome-extension.zip  Chromium 扩展（MV3，content
 *                     script 注入 MAIN world；扩展页拖入/加载已解压，无需 Tampermonkey）
 *  3. web/dtc-bridge.user.js   浏览器用户脚本（Tampermonkey 拖入即装）
 *  4. web/dtc-bridge.bookmarklet.html  书签栏拖拽版（零扩展依赖，点一下即注入）
 *
 * 各形态与 console 粘贴版共享同一份打包结果（plugin/src 多文件，esbuild 打成单个脚本）。
 */
import fs from "node:fs";
import path from "node:path";
import { execSync } from "node:child_process";
import { fileURLToPath, pathToFileURL } from "node:url";
import { channelGuideLines } from "../channel-guide.js";
import { ensureRelayToken, injectRelayToken } from "../relay-token.js";

export interface PluginOptions {
  src?: string;
  dist?: string;
}

const VERSION = "0.1.0";

interface EsbuildApi {
  build: (options: Record<string, unknown>) => Promise<{ outputFiles?: Array<{ text: string }> }>;
}

function findRepoRoot(fromFile: string): string {
  let dir = path.dirname(fromFile);
  for (let i = 0; i < 8; i++) {
    if (
      fs.existsSync(path.join(dir, "plugin", "src", "manifest.json")) &&
      fs.existsSync(path.join(dir, "package.json"))
    ) {
      return dir;
    }
    const parent = path.dirname(dir);
    if (parent === dir) break;
    dir = parent;
  }
  throw new Error(`找不到仓库根目录（从 ${fromFile} 向上）`);
}

async function loadEsbuild(repoRoot: string): Promise<EsbuildApi> {
  const esbuildEntry = path.join(repoRoot, "node_modules", "esbuild", "lib", "main.js");
  if (!fs.existsSync(esbuildEntry)) {
    throw new Error(`找不到 esbuild：${esbuildEntry}`);
  }
  const mod = (await import(pathToFileURL(esbuildEntry).href)) as { default?: EsbuildApi } & EsbuildApi;
  const esbuild = typeof mod.build === "function" ? mod : mod.default;
  if (!esbuild || typeof esbuild.build !== "function") throw new Error("esbuild.build 不可用");
  return esbuild;
}

/** 把 plugin/src/main.js 及其命令模块打成 Figma 能加载的单个脚本。 */
export async function bundlePluginCode(srcDir: string): Promise<string> {
  const entry = path.join(srcDir, "main.js");
  if (!fs.existsSync(entry)) throw new Error(`插件入口不存在：${entry}`);
  const esbuild = await loadEsbuild(findRepoRoot(fileURLToPath(import.meta.url)));
  const result = await esbuild.build({
    absWorkingDir: srcDir,
    entryPoints: [entry],
    bundle: true,
    format: "iife",
    platform: "neutral",
    target: "es2020",
    write: false,
    legalComments: "none",
    sourcemap: false,
    logLevel: "silent",
  });
  const text = result.outputFiles?.[0]?.text;
  if (!text) throw new Error("esbuild 没有产出插件脚本");
  return text;
}

/** 控制台应急脚本：同一份打包结果，前面补上本次构建的 ui.html。 */
export function renderConsoleInjection(uiHtml: string, codeJs: string): string {
  return (
    "// Generated by dtc plugin build. Paste the whole file into the Figma plugin console.\n" +
    "// 与 desktop/code.js 同一份打包结果；__html__ 是同一次构建写入口令后的 ui.html。\n" +
    "var __html__ = " +
    JSON.stringify(uiHtml) +
    ";\n" +
    codeJs
  );
}

/** 诊断面板（自动重连、channel 固定、日志流）——与桌面插件共用同一份 ui.html */

function userscriptHeader(): string {
  return `// ==UserScript==
// @name         Design-to-Code Bridge (dtc)
// @namespace    https://github.com/Ybqac/design-to-code
// @version      ${VERSION}
// @description  Figma ↔ 本地 dtc CLI 通道：自动注入增强插件（富字段提取 + SVG 导出），channel 默认 dtc，断线自动重连
// @author       design-to-code (fork of grab/cursor-talk-to-figma-mcp, MIT)
// @match        https://www.figma.com/file/*
// @match        https://www.figma.com/design/*
// @match        https://www.figma.com/board/*
// @match        https://www.figma.com/proto/*
// @run-at       document-idle
// @grant        none
// ==/UserScript==`;
}

export async function runPlugin(action: string, opts: PluginOptions): Promise<void> {
  const repoRoot = findRepoRoot(fileURLToPath(import.meta.url));
  const srcDir = path.resolve(opts.src ?? path.join(repoRoot, "plugin", "src"));
  const distDir = path.resolve(opts.dist ?? path.join(repoRoot, "plugin", "build"));

  const codeJs = await bundlePluginCode(srcDir);
  const relayToken = ensureRelayToken();
  const uiHtml = injectRelayToken(fs.readFileSync(path.join(srcDir, "ui.html"), "utf8"), relayToken);
  const manifest = JSON.parse(fs.readFileSync(path.join(srcDir, "manifest.json"), "utf8"));

  if (action === "build") {
    // 1. desktop 插件包。ui.html 里的口令占位符已换成 ~/.dtc/relay.token，源码不写口令。
    const desktopDir = path.join(distDir, "desktop");
    fs.mkdirSync(desktopDir, { recursive: true });
    fs.writeFileSync(path.join(desktopDir, "code.js"), codeJs);
    fs.writeFileSync(path.join(desktopDir, "ui.html"), uiHtml);
    fs.copyFileSync(path.join(srcDir, "manifest.json"), path.join(desktopDir, "manifest.json"));

    // 2. 桥接注入体（f2c 式常驻 overlay：面板 + 无限等待注入 + 无限退避重连）
    //    payload 由 overlay 在 window.figma 就绪时调用（不再一次性注入、无超时上限）
    const overlayJs = injectRelayToken(fs.readFileSync(path.join(srcDir, "overlay.js"), "utf8"), relayToken);
    const payloadRunner = `window.__dtcRunPayload = function () {
  window.__dtcOverlay = true;
  var __html__ = "";
${codeJs
  .split("\n")
  .map((l) => "  " + l)
  .join("\n")}
};`
    const body = payloadRunner + "\n" + overlayJs;

    const webDir = path.join(distDir, "web");
    fs.mkdirSync(webDir, { recursive: true });
    fs.writeFileSync(path.join(webDir, "console-injection.js"), renderConsoleInjection(uiHtml, codeJs));

    // 2a. .user.js（Tampermonkey 用户脚本）
    const userJs = `${userscriptHeader()}
${body}`;
    fs.writeFileSync(path.join(webDir, "dtc-bridge.user.js"), userJs);

    // 2b. Chromium 扩展（MV3，content script 注入 MAIN world，无需 Tampermonkey；
    //     打包 zip 供"加载已解压的扩展程序/拖入扩展页"安装）
    const chromeDir = path.join(distDir, "chrome-extension");
    fs.mkdirSync(chromeDir, { recursive: true });
    fs.writeFileSync(
      path.join(chromeDir, "manifest.json"),
      JSON.stringify(
        {
          manifest_version: 3,
          name: "Design-to-Code Bridge",
          version: VERSION,
          description: "Figma ↔ dtc CLI 通道：自动注入 bridge（channel 默认 dtc，自动重连）",
          content_scripts: [
            {
              matches: [
                "https://www.figma.com/file/*",
                "https://www.figma.com/design/*",
                "https://www.figma.com/board/*",
                "https://www.figma.com/proto/*",
              ],
              js: ["content.js"],
              run_at: "document_idle",
              world: "MAIN",
              all_frames: false,
            },
          ],
        },
        null,
        2,
      ) + "\n",
    );
    fs.writeFileSync(path.join(chromeDir, "content.js"), body);
    const zipPath = path.join(distDir, "dtc-bridge-chrome-extension.zip");
    try {
      fs.rmSync(zipPath, { force: true });
      execSync(`cd ${JSON.stringify(chromeDir)} && zip -qr ${JSON.stringify(zipPath)} .`, { stdio: "pipe" });
      console.log(`→ Chrome 扩展包: ${zipPath}`);
    } catch {
      console.warn(`⚠️ 系统 zip 命令不可用，未打包 zip（${chromeDir} 目录仍可直接"加载已解压的扩展程序"）`);
    }

    // 3. bookmarklet 页面（payload 打进 javascript: URL，拖到书签栏即用）
    const bookmarklet = `javascript:${encodeURIComponent(`(function(){${body.replace(/\/\/[^\n]*/g, "")}})();`)}void 0;`;
    const bmPage = `<!DOCTYPE html>
<html lang="zh">
<head><meta charset="utf-8"><title>dtc bridge 书签安装</title>
<style>body{font:15px/1.7 -apple-system,sans-serif;max-width:720px;margin:48px auto;padding:0 20px;color:#111}
a.bookmark{display:inline-block;padding:12px 20px;background:#2563eb;color:#fff;border-radius:10px;text-decoration:none;font-weight:600}
code{background:#f1f5f9;padding:2px 6px;border-radius:4px}</style>
</head>
<body>
<h1>dtc bridge · 书签栏安装</h1>
<ol>
  <li>把下面这个按钮<strong>拖到浏览器的书签栏</strong>：</li>
  <p><a class="bookmark" href="${bookmarklet}">▶ dtc bridge</a></p>
  <li>打开 figma.com 的设计文件页面，点一下书签栏里的「dtc bridge」即完成注入（channel 默认 <code>dtc</code>，连 <code>ws://127.0.0.1:3055</code>）。口令在本次构建时写入，不用手填。</li>
  <li>每次刷新页面后需要再点一次（书签版不自动注入；想要全自动请用 <code>dtc-bridge.user.js</code> 用户脚本版）。</li>
</ol>
<h2>验证</h2>
<p>终端运行 <code>dtc doctor</code>——relay 与插件都 ✅ 即通道就绪。</p>
</body>
</html>
`;
    fs.writeFileSync(path.join(webDir, "dtc-bridge.bookmarklet.html"), bmPage);

    // 4. web 安装说明
    fs.writeFileSync(
      path.join(webDir, "README.md"),
      `# 通道安装（装一次，长期用）

## 主推：Figma 桌面 App
Figma 桌面 App → Plugins → Development → Import plugin from manifest → 选 \`../desktop/manifest.json\`（一次导入永久用）。口令已写入这个构建产物，重新打开插件即可。

## 次级

### 扩展
产物：\`../dtc-bridge-chrome-extension.zip\`（源目录 \`../chrome-extension/\`）
1. 解压 zip 得到 chrome-extension 文件夹。
2. 打开 \`chrome://extensions\`，开启「开发者模式」。
3. 把文件夹拖入扩展页，或点「加载已解压的扩展程序」选择该文件夹。
4. 打开 figma.com 设计文件，右上角绿色角标 \`dtc: ✅ channel dtc 已就绪\` 即成功
   （角标可点击切换 channel；断线自动重连；relay 需先 \`dtc relay start\`，3055 已占用则复用）。
注意：开发者模式安装的扩展，Chrome 启动时可能提示「关闭开发者模式扩展」——选择保留即可。
不需要用「打包扩展程序」按钮：它生成 .crx（商店分发格式），本地 .crx 会被 Chrome 拦截。

### 用户脚本（Tampermonkey）
1. 安装 [Tampermonkey](https://www.tampermonkey.net/) 浏览器扩展（一次）。
2. 把 \`dtc-bridge.user.js\` **拖入浏览器窗口**（或 Tampermonkey 面板 → 添加新脚本 → 粘贴全文 → 保存）。

### 书签栏
打开 \`dtc-bridge.bookmarklet.html\`，把「▶ dtc bridge」按钮拖到书签栏；在 Figma 页面点一下即注入（每次刷新后需重点一次）。

## 兜底链
1. Figma 桌面 App → Plugins → Development → Import plugin from manifest（主推，不依赖页面注入）
2. Chromium 扩展
3. 用户脚本 dtc-bridge.user.js
4. 书签
5. 旧式 console 粘贴：同目录 \`console-injection.js\`（与 desktop/code.js 同一份打包，构建时生成）

## 注入机制说明（重要）
浏览器页面上下文是否存在 \`figma\` 插件全局对象由 Figma web 端决定。历史上 console 粘贴
\`console-injection.js\` 可用（本仓库实测），扩展/用户脚本以相同上下文注入，理论等价；但 Figma
前端变更可能使其失效。角标自诊断会明确提示；失效时走主推（桌面 App Import manifest）。
排错见仓库 README「排错」。
`,
    );

    console.log(`✅ plugin build → ${distDir}/`);
    console.log(`   desktop/                          主推 · Figma 桌面 App：Plugins → Development → Import plugin from manifest`);
    console.log(`   dtc-bridge-chrome-extension.zip   Chromium 扩展：chrome://extensions 开发者模式 → 拖入/加载已解压`);
    console.log(`   web/dtc-bridge.user.js            用户脚本（Tampermonkey 拖入即装）`);
    console.log(`   web/dtc-bridge.bookmarklet.html   书签栏版（零扩展，点一下注入）`);
    console.log(`   web/console-injection.js          控制台应急粘贴（与 desktop/code.js 同一份打包）`);
    console.log(`   web/README.md                     安装与机制说明`);
  } else if (action === "install") {
    await runPlugin("build", opts);
    console.log(`
📦 通道安装（channel 默认 dtc，与 dtc extract --channel 一致）

${channelGuideLines(distDir).join("\n")}

relay：dtc relay start（3055 已被占用则复用，不重复启动）
验证：dtc doctor
排错：仓库 README「排错」
插件名：${manifest.name}
`);
  } else {
    throw new Error(`未知 action: ${action}（支持 build | install）`);
  }
}
